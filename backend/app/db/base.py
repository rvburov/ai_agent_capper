"""Базовый класс моделей SQLAlchemy и общие типы колонок.

Имена ограничений и индексов задаются naming_convention: так Alembic создает и удаляет
их предсказуемо. Типы по аннотациям: datetime → timestamptz, dict → JSONB.
Деньги, кэфы и доллары ИИ — через Annotated-типы ниже, чтобы точность была одна везде.
"""

from datetime import date, datetime
from decimal import Decimal
from typing import Annotated, Any, ClassVar

from sqlalchemy import (
    CHAR,
    BigInteger,
    Boolean,
    CheckConstraint,
    Date,
    DateTime,
    Double,
    Identity,
    Integer,
    MetaData,
    Numeric,
    String,
    Text,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

CURRENCIES = ("RUB", "USD", "EUR")

# Первичный ключ: BIGINT GENERATED BY DEFAULT AS IDENTITY
BigIntPK = Annotated[int, mapped_column(BigInteger, Identity(always=False), primary_key=True)]
# Деньги банка и ставок в валюте программы
Money = Annotated[Decimal, mapped_column(Numeric(12, 2))]
# Кэф букмекера
Odds = Annotated[Decimal, mapped_column(Numeric(6, 3))]
# Стоимость вызовов Claude в долларах
UsdCost = Annotated[Decimal, mapped_column(Numeric(12, 6))]
# Лимиты и бюджеты на Claude в долларах
UsdLimit = Annotated[Decimal, mapped_column(Numeric(10, 2))]
# Код валюты: RUB, USD или EUR
CurrencyCode = Annotated[str, mapped_column(CHAR(3))]
# Адрес IPv4 или IPv6 строкой (нормализует deps.client_ip)
IpAddress = Annotated[str, mapped_column(String(45))]
# sha256 или HMAC-SHA256 в hex
Hash64 = Annotated[str, mapped_column(String(64))]


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    type_annotation_map: ClassVar[dict[Any, Any]] = {
        datetime: DateTime(timezone=True),
        date: Date,
        dict[str, Any]: JSONB,
        bool: Boolean,
        int: Integer,
        float: Double,
        str: Text,
    }


class CreatedAtMixin:
    """created_at timestamptz NOT NULL DEFAULT now()."""

    created_at: Mapped[datetime] = mapped_column(server_default=func.now())


class UpdatedAtMixin:
    """updated_at обновляется ORM при каждом изменении строки."""

    updated_at: Mapped[datetime] = mapped_column(server_default=func.now(), onupdate=func.now())


def check_in(column: str, values: tuple[str, ...] | tuple[int, ...], name: str) -> CheckConstraint:
    """CHECK (column IN (...)) — перечисления хранятся строкой, не enum PostgreSQL."""
    rendered = ", ".join(f"'{v}'" if isinstance(v, str) else str(v) for v in values)
    return CheckConstraint(f"{column} IN ({rendered})", name=name)


def check_probability(column: str) -> CheckConstraint:
    return CheckConstraint(f"{column} >= 0 AND {column} <= 1", name=f"{column}_range")
